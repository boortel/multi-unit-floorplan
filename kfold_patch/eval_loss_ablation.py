"""
Test-set evaluation of the loss-ablation retraining (docs/ABLATION_PLAN.md §9).

For every models/{m}_lossabl_{m}_{variant}_v2m_*/{fold} it computes the pooled-CM metrics on the CubiCasa5k
test set (same path as evaluate_kfold.evaluate_fold, via ablation_inference.evaluate) plus per-image
latency, and compares with the full-loss champion fold models (reference fold CMs, same folds).

    CUDA_VISIBLE_DEVICES=2 python kfold_patch/eval_loss_ablation.py            # evaluate (resumable) + summary
    python kfold_patch/eval_loss_ablation.py --summary_only

Run one job per GPU, with nothing else on that GPU, so the latency numbers are clean.
"""
import argparse
import glob
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)
sys.path.insert(0, os.path.dirname(_HERE))

import numpy as np  # noqa: E402

OUT_DIR = 'results/loss_ablation'
VARIANTS = {'auf': 'L1: focal (aUF) + AWL', 'auf_aaf': 'L2: focal + AAF + AWL', 'full': 'L3: focal + AAF + heatmap (champion)'}
CLASSES = ['bg', 'walls', 'railings', 'doors', 'windows', 'stairs']


def run_dir(model, variant, fold):
    c = sorted(glob.glob(f'models/{model}_lossabl_{model}_{variant}_v2m_*/{fold}/training_cfg.py'))
    assert len(c) == 1, (model, variant, fold, c)
    return os.path.dirname(c[0])


def epochs_trained(d):
    import tensorflow as tf
    n = 0
    for ev in glob.glob(os.path.join(d, 'validation', 'events*')):
        for e in tf.compat.v1.train.summary_iterator(ev):
            if any(v.tag == 'epoch_loss' for v in e.summary.value):
                n = max(n, e.step + 1)
    return n


def evaluate_all(models, folds, variants):
    import tensorflow as tf
    import ablation_inference as A
    test = A.load_split('test', 0)
    assert len(test) == 400, len(test)
    os.makedirs(OUT_DIR, exist_ok=True)
    for m in models:
        champs = A.fold_dirs(m)
        for f in folds:
            for v in variants:
                path = os.path.join(OUT_DIR, f'{m}_{v}_fold{f}.json')
                if os.path.exists(path):
                    continue
                d = champs[f] if v == 'full' else run_dir(m, v, f)
                model = tf.keras.models.load_model(d, compile=False)
                cm, timing = A.evaluate(model, test)
                rec = dict(model=m, variant=v, fold=f, checkpoint=d, epochs_trained=epochs_trained(d),
                           n_test_images=len(test), cm=cm.tolist(), timing=timing, **A.device_info(), **A.summary(cm))
                rec['note'] = 'evaluated alone on an otherwise idle GPU'
                if v == 'full':
                    ref = np.load(A.REFERENCE[m] + '_fold_cms.npy')[f]
                    rec['reference_cm_rel_diff'] = float(np.abs(ref - cm).sum() / ref.sum())
                with open(path + '.tmp', 'w') as fh:
                    json.dump(rec, fh)
                os.replace(path + '.tmp', path)
                print(f'[{m} {v} f{f}] mIoU(fg)={rec["mean_fg_iou"]:.4f} acc={rec["pixel_acc"]:.4f} '
                      f'epochs={rec["epochs_trained"]} {timing["ms_median"]:.1f} ms/img', flush=True)
                del model
                tf.keras.backend.clear_session()


def metrics(cm):
    cm = np.asarray(cm, dtype=np.float64)
    tp = np.diag(cm)
    iou = tp / np.maximum(cm.sum(0) + cm.sum(1) - tp, 1)
    rec = tp / np.maximum(cm.sum(1), 1)
    return dict(acc=tp.sum() / cm.sum(), mca=rec[1:].mean(), miou=iou[1:].mean(), miou_all=iou.mean(), iou=iou)


def summarize():
    rows = {}
    for p in glob.glob(os.path.join(OUT_DIR, '*_fold*.json')):
        r = json.load(open(p))
        rows.setdefault((r['model'], r['variant']), {})[r['fold']] = r
    out = ['# Loss ablation (retrained, CubiCasa5k test set)', '',
           'Generated by `kfold_patch/eval_loss_ablation.py`. Plan: `docs/ABLATION_PLAN.md` §9/§13. '
           'Metrics from the confusion matrix pooled over folds 0–4 (400 test images per fold). '
           'Mean class acc and mean IoU (fg) are over the 5 foreground classes; mIoU (all) includes background. '
           'Δ = variant − champion (L3) in pp on the same folds; fold std = std of the per-fold Δ mIoU (fg). '
           'ms/img = median over folds of the per-image median forward pass + argmax (batch 1, 768×768, '
           '5 warm-up images excluded), each model evaluated alone on an idle GPU. Epochs = epochs actually '
           'trained (early stopping, patience 30 on val loss, last-epoch weights).', '']
    for m in ('cab1', 'cab2'):
        ref = rows.get((m, 'full'), {})
        if not ref:
            continue
        out += [f'## {m.upper()}', '',
                '| Variant | Folds | Epochs | Pixel acc | Mean class acc | mIoU (fg) | mIoU (all) | Δ mIoU fg (pp) '
                '| Δ fold std | worse in | ms/img | ' + ' | '.join(f'{c} IoU' for c in CLASSES[1:]) + ' |',
                '|' + '---|' * (12 + len(CLASSES) - 1)]
        for v in ('auf', 'auf_aaf', 'full'):
            recs = rows.get((m, v))
            if not recs:
                continue
            folds = sorted(f for f in recs if f in ref)
            mt = metrics(sum(np.asarray(recs[f]['cm']) for f in folds))
            mr = metrics(sum(np.asarray(ref[f]['cm']) for f in folds))
            per = [metrics(recs[f]['cm'])['miou'] - metrics(ref[f]['cm'])['miou'] for f in folds]
            d = s = w = ''
            if v != 'full':
                d = f'{100 * (mt["miou"] - mr["miou"]):+.2f}'
                s = f'{100 * np.std(per):.2f}'
                w = f'{sum(x < 0 for x in per)}/{len(per)}'
            ep = ','.join(str(recs[f]['epochs_trained']) for f in folds)
            ms = np.median([recs[f]['timing']['ms_median'] for f in folds])
            out.append(f'| {VARIANTS[v]} | {len(folds)} | {ep} | {100 * mt["acc"]:.2f} | {100 * mt["mca"]:.2f} | '
                       f'{100 * mt["miou"]:.2f} | {100 * mt["miou_all"]:.2f} | {d} | {s} | {w} | {ms:.1f} | '
                       + ' | '.join(f'{100 * x:.1f}' for x in mt['iou'][1:]) + ' |')
        out.append('')
    path = os.path.join(OUT_DIR, 'SUMMARY.md')
    with open(path, 'w') as fh:
        fh.write('\n'.join(out))
    print('\n'.join(out))
    print(f'\nSaved {path}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--models', nargs='*', default=['cab1', 'cab2'])
    ap.add_argument('--folds', nargs='*', type=int, default=[0, 1, 2, 3, 4])
    ap.add_argument('--variants', nargs='*', default=['full', 'auf', 'auf_aaf'])
    ap.add_argument('--summary_only', action='store_true')
    args = ap.parse_args()
    if not args.summary_only:
        evaluate_all(args.models, args.folds, args.variants)
    summarize()


if __name__ == '__main__':
    main()
